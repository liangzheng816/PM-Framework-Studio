function main(): void {
  const check = process.argv.includes("--check");
  if (!existsSync(RAW_DIR)) {
    throw new Error(`RAW directory not found: ${RAW_DIR}`);
  }

  const digests = readdirSync(RAW_DIR)
    .map(parseDigest)
    .filter((d): d is Digest => d !== null)
    .sort((a, b) => (a.stamp < b.stamp ? 1 : -1)); // newest first

  if (digests.length === 0) {
    throw new Error(
      `No dashboards matching ai-intel-dashboard-YYYYMMDD-HHMMSS.html in ${RAW_DIR}`,
    );
  }

  const html = buildIndex(digests);
  const indexCurrent = existsSync(INDEX_FILE) ? readFileSync(INDEX_FILE, "utf8") : "";

  // Themed pages: compare desired vs on-disk.
  const pages = digests.map((d) => {
    const path = join(PAGES_DIR, d.pageFile);
    const desired = renderPage(d);
    const current = existsSync(path) ? readFileSync(path, "utf8") : "";
    return { d, path, desired, stale: desired !== current };
  });
  const stalePages = pages.filter((p) => p.stale);

  if (check) {
    const problems: string[] = [];
    if (html !== indexCurrent) problems.push("ai-weekly/index.html");
    for (const p of stalePages) problems.push(`pages/${p.d.pageFile}`);
    if (problems.length > 0) {
      console.error(
        `AI Weekly out of date (${problems.join(", ")}). Run: npm run build:ai-weekly`,
      );
      process.exit(1);
    }
    console.log("AI Weekly index and pages are up to date.");
    return;
  }

  if (!existsSync(PAGES_DIR)) mkdirSync(PAGES_DIR, { recursive: true });
  for (const p of stalePages) {
    writeFileSync(p.path, p.desired, "utf8");
  }
  if (html !== indexCurrent) {
    writeFileSync(INDEX_FILE, html, "utf8");
  }
  console.log(
    `AI Weekly: ${digests.length} issue(s); index ${
      html !== indexCurrent ? "written" : "unchanged"
    }; wrote ${stalePages.length} themed page(s)` +
      (stalePages.length
        ? `: ${stalePages.map((p) => p.d.pageFile).join(", ")}`
        : "."),
  );
}

main();
