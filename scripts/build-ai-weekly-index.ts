/**
 * Regenerates the AI Weekly landing page (public/ai-weekly/index.html) and
 * polishes every dashboard under public/ai-weekly/RAW/ to match the site's
 * editorial paper theme.
 *
 * Workflow:
 *   1. Scan public/ai-weekly/RAW/*.html for AI Intel Weekly Dashboards.
 *   2. Parse the timestamp from each filename
 *      (ai-intel-dashboard-YYYYMMDD-HHMMSS.html) plus light metadata from the
 *      HTML (title, "as of" date, source count, "top X of Y" candidates).
 *   3. Write a fully themed copy of each dashboard into public/ai-weekly/pages/
 *      named ai-weekly-digest-YYYYMMDD-HHMMSS.html (same timestamp suffix). The
 *      copy gets the editorial paper palette/fonts + a back-to-index site strip
 *      injected between marker comments. RAW/ is left pristine as the source.
 *   4. Rebuild index.html: a hero, a derived stats bar, and one card per
 *      dashboard sorted newest-first, linking into pages/.
 *
 * Usage:
 *   npx tsx scripts/build-ai-weekly-index.ts          # write changes
 *   npx tsx scripts/build-ai-weekly-index.ts --check   # fail if out of date
 *
 * Dashboard HTML is machine-generated by an external pipeline and is treated
 * as trusted local content. Only run this on your own files.
 */

