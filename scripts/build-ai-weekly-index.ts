/** Build the themed page HTML for a digest from its pristine RAW source. */
function renderPage(d: Digest): string {
  let html = readFileSync(join(RAW_DIR, d.file), "utf8");

  // 1) Theme override + fonts before </head>.
  const headBody = `${FONT_LINKS}\n${THEME_OVERRIDE}`;
  html = html.replace(
    /<\/head>/i,
    `<!-- SITE-THEME:START -->\n${headBody}\n<!-- SITE-THEME:END -->\n</head>`,
  );

  // 2) Global navbar + site strip right after <body>.
  html = html.replace(
    /<body[^>]*>/i,
    (m) =>
      `${m}\n${NAV_BLOCK}\n<!-- SITE-STRIP:START -->\n${SITE_STRIP}\n<!-- SITE-STRIP:END -->`,
  );

  return html;
}

