const FILE_RE = /^ai-intel-dashboard-(\d{8})-(\d{6})\.html$/i;

interface Digest {
  /** Source filename in RAW/, e.g. ai-intel-dashboard-20260530-225115.html. */
  file: string;
  /** Themed output filename in pages/, e.g. ai-weekly-digest-20260530-225115.html. */
  pageFile: string;
  /** Sortable key: YYYYMMDDHHMMSS from the filename. */
  stamp: string;
  /** Display date "2026 · 05 · 30". */
  date: string;
  /** Display time "14:51 UTC" (from the dashboard, falls back to filename). */
  time: string;
  title: string;
  sources: number;
  topN: number | null;
  total: number | null;
}

function match1(html: string, re: RegExp): string | null {
  const m = html.match(re);
  return m ? m[1].trim() : null;
}

function parseDigest(file: string): Digest | null {
  const m = file.match(FILE_RE);
  if (!m) return null;
  const [, d, t] = m;
  const html = readFileSync(join(RAW_DIR, file), "utf8");

  const title =
    match1(html, /<title>([^<]*?)\s*(?:-|–|\u2013)?\s*\d{4}-\d{2}-\d{2}[^<]*<\/title>/i) ??
    match1(html, /<title>([^<]+)<\/title>/i) ??
    "AI Intelligence Weekly Digest";

  // Time of day: prefer the <span class="timestamp"> in the report header.
  const tsSpan = match1(html, /<span class="timestamp">([^<]+)<\/span>/i);
  let time = `${t.slice(0, 2)}:${t.slice(2, 4)} UTC`;
  if (tsSpan) {
    const tm = tsSpan.match(/(\d{2}:\d{2})\s*UTC/i);
    if (tm) time = `${tm[1]} UTC`;
  }

  const sourcesLine = match1(html, /Sources:\s*([^<]+)</i);
  const sources = sourcesLine
    ? sourcesLine.split(",").map((s) => s.trim()).filter(Boolean).length
    : 0;

  const showing = html.match(/Showing:\s*top\s*(\d+)\s*of\s*(\d+)/i);
  const topN = showing ? Number(showing[1]) : null;
  const total = showing ? Number(showing[2]) : null;

  return {
    file,
    pageFile: `ai-weekly-digest-${d}-${t}.html`,
    stamp: `${d}${t}`,
    date: `${d.slice(0, 4)} · ${d.slice(4, 6)} · ${d.slice(6, 8)}`,
    time,
    title,
    sources,
    topN,
    total,
  };
}

